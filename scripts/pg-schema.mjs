// Generates prisma/postgres/schema.prisma from the SQLite dev schema (single source of truth).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const src = readFileSync(new URL("../prisma/schema.prisma", import.meta.url), "utf8");
const out = src.replace(
  /datasource db \{[\s\S]*?\}/,
  `datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DATABASE_URL_UNPOOLED")\n}`,
);
mkdirSync(new URL("../prisma/postgres/", import.meta.url), { recursive: true });
writeFileSync(new URL("../prisma/postgres/schema.prisma", import.meta.url), `// GENERATED by scripts/pg-schema.mjs — edit prisma/schema.prisma instead.\n${out}`);
console.log("prisma/postgres/schema.prisma written");
